"""Deterministic calibration and untouched holdout evaluation for versioned models."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
import sklearn
from sklearn.metrics import confusion_matrix, precision_recall_fscore_support
from sklearn.model_selection import train_test_split

from app.ml.features import FEATURE_DEFINITION_VERSION, FEATURE_NAMES, feature_matrix
from app.ml.registry import load_model
from app.ml.train import generate_synthetic_dataset, write_dataset

EVALUATION_VERSION = "threshold_evaluation.v1"
EVALUATION_SEED = 20261026
MAX_ALERT_RATE = 0.15


def evaluation_data() -> list[dict]:
    """Independent labeled scenarios, including overlapping legitimate/risky behavior."""
    rows = generate_synthetic_dataset(2160, 240, seed=EVALUATION_SEED)
    rng = np.random.default_rng(EVALUATION_SEED)
    for index, row in enumerate(rows):
        row["transaction_id"] = f"eval-v1-{index:05d}"
        # Fixed evaluation period is disjoint from training (January 2025).
        row["occurred_at"] = f"2025-02-{1 + index // 144:02d}T{index % 24:02d}:00:00Z"
        row["country"] = str(rng.choice(["US", "GB", "CA"]))
        row["payment_method"] = str(rng.choice(["card", "bank_transfer", "wallet"]))
        row["scenario"] = "obvious_anomaly" if row["is_anomaly"] else "ordinary_purchase"
        if not row["is_anomaly"] and index % 13 == 0:
            row["scenario"] = "legitimate_large_travel_purchase"
            row["transaction_amount"] *= 5
            row["amount_difference_from_customer_average"] = row["transaction_amount"] * 0.8
            row["country_change"] = 1
            row["new_device_indicator"] = 1
        if row["is_anomaly"] and index % 3 == 0:
            # Subtle fraud resembles ordinary purchases; labels are scenario truth,
            # never generated by thresholding model scores.
            normal = rows[index % 2160]
            for name in FEATURE_NAMES:
                row[name] = normal[name]
            row["transaction_amount"] *= 1.25
            row["scenario"] = "subtle_account_takeover"
    return rows


def classification_metrics(labels, scores, threshold: float) -> dict:
    labels = np.asarray(labels)
    scores = np.asarray(scores, dtype=float)
    if labels.ndim != 1 or scores.shape != labels.shape or not len(labels):
        raise ValueError("labels and scores must be nonempty aligned vectors")
    if not np.isin(labels, [0, 1]).all() or not np.isfinite(scores).all():
        raise ValueError("labels must be binary and scores finite")
    if not np.isfinite(threshold):
        raise ValueError("threshold must be finite")
    predictions = scores >= threshold
    tn, fp, fn, tp = confusion_matrix(labels, predictions, labels=[0, 1]).ravel()
    precision, recall, f1, _ = precision_recall_fscore_support(
        labels, predictions, average="binary", zero_division=0
    )
    return {
        "rows": len(labels),
        "true_positives": int(tp),
        "false_positives": int(fp),
        "true_negatives": int(tn),
        "false_negatives": int(fn),
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "alert_count": int(predictions.sum()),
        "alert_rate": float(predictions.mean()),
        "alerts_per_10000_transactions": float(predictions.mean() * 10000),
    }


def select_threshold(labels, scores) -> tuple[float, list[dict]]:
    scores = np.asarray(scores, dtype=float)
    # Unique observed cutoffs plus an all-negative candidate enumerate every
    # attainable prediction set for the inclusive comparator, even with ties.
    candidates = np.append(np.unique(scores), np.nextafter(scores.max(), np.inf))
    sweep = [
        {"threshold": float(value), **classification_metrics(labels, scores, float(value))}
        for value in candidates
    ]
    eligible = [item for item in sweep if item["alert_rate"] <= MAX_ALERT_RATE]
    best = max(eligible, key=lambda item: (item["f1"], item["precision"], item["threshold"]))
    return best["threshold"], sweep


def run_evaluation(root: Path) -> dict:
    artifacts = root / "model-artifacts"
    metadata_path = artifacts / "isolation_forest.v1.metadata.json"
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    if metadata["feature_definition_version"] != FEATURE_DEFINITION_VERSION:
        raise ValueError("model feature version does not match evaluation")
    if metadata["feature_names"] != list(FEATURE_NAMES):
        raise ValueError("model feature order does not match evaluation")
    version = metadata["model_version"]
    model_path = artifacts / f"{version}.joblib"
    model = load_model(model_path)
    rows = evaluation_data()
    dataset_path = root / "data" / "synthetic" / f"{EVALUATION_VERSION}.csv"
    write_dataset(rows, dataset_path)
    scores = -model.decision_function(feature_matrix(rows))
    labels = np.asarray([row["is_anomaly"] for row in rows])
    calibration, holdout = train_test_split(
        np.arange(len(rows)), test_size=0.5, stratify=labels, random_state=EVALUATION_SEED
    )
    threshold, sweep = select_threshold(labels[calibration], scores[calibration])
    report = {
        "evaluation_version": EVALUATION_VERSION,
        "model_version": version,
        "calibration": classification_metrics(labels[calibration], scores[calibration], threshold),
        "holdout": classification_metrics(labels[holdout], scores[holdout], threshold),
        "baseline_holdout_at_zero": classification_metrics(labels[holdout], scores[holdout], 0.0),
        "segments": {},
        "error_review": {},
    }
    for dimension in ("country", "payment_method"):
        groups = []
        for value in sorted({row[dimension] for row in rows}):
            cal = np.asarray([i for i in calibration if rows[i][dimension] == value])
            test = np.asarray([i for i in holdout if rows[i][dimension] == value])
            candidate, _ = select_threshold(labels[cal], scores[cal])
            groups.append(
                {
                    "segment": value,
                    "candidate_threshold": candidate,
                    "calibration": classification_metrics(labels[cal], scores[cal], candidate),
                    "holdout_global": classification_metrics(labels[test], scores[test], threshold),
                    "holdout_candidate": classification_metrics(
                        labels[test], scores[test], candidate
                    ),
                    "decision": "retain_global_pending_representative_production_labels",
                }
            )
        report["segments"][dimension] = groups
    review_rows = []
    for name, truth, prediction in (("false_positives", 0, True), ("false_negatives", 1, False)):
        errors = sorted(
            [i for i in holdout if labels[i] == truth and (scores[i] >= threshold) == prediction],
            key=lambda i: (-scores[i] if prediction else scores[i], rows[i]["transaction_id"]),
        )
        scenarios = sorted({rows[i]["scenario"] for i in errors})
        report["error_review"][name] = {
            "count": len(errors),
            "by_scenario": {
                scenario: sum(rows[i]["scenario"] == scenario for i in errors)
                for scenario in scenarios
            },
            "examples": [rows[i] | {"score": float(scores[i])} for i in errors[:10]],
        }
        review_rows.extend(
            rows[i] | {"score": float(scores[i]), "error_type": name} for i in errors
        )
    config = {
        "configuration_version": "anomaly_threshold.v1",
        "model_version": version,
        "model_sha256": hashlib.sha256(model_path.read_bytes()).hexdigest(),
        "feature_definition_version": FEATURE_DEFINITION_VERSION,
        "threshold": threshold,
        "comparator": ">=",
        "score_definition": "negative decision_function; larger means more anomalous",
        "selection": (
            "maximize calibration F1 subject to alert_rate <= 0.15; "
            "ties prefer precision then higher threshold"
        ),
        "maximum_calibration_alert_rate": MAX_ALERT_RATE,
        "seed": EVALUATION_SEED,
        "dataset_sha256": hashlib.sha256(dataset_path.read_bytes()).hexdigest(),
        "evaluation_version": EVALUATION_VERSION,
        "segment_overrides": {},
        "segment_decision": (
            "Global threshold retained: small synthetic segments cannot justify "
            "production overrides."
        ),
        "deployment_status": (
            "evaluated_candidate; existing worker scoring and metrics are unchanged"
        ),
        "library_versions": {"numpy": np.__version__, "scikit_learn": sklearn.__version__},
    }
    report["configuration"] = config
    for suffix, content in (
        ("threshold", config),
        ("threshold-report", report),
        ("threshold-sweep", sweep),
    ):
        (artifacts / f"{version}.{suffix}.json").write_text(
            json.dumps(content, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8"
        )
    if review_rows:
        write_dataset(review_rows, root / "data" / "processed" / f"{EVALUATION_VERSION}.errors.csv")
    return report
